def name_matches(brand_name: str, keyword: str) -> bool:
    """品牌名是否匹配关键词：精确匹配 or 关键词后紧跟空格/括号/英文，避免短词误匹配"""
    bn = brand_name.strip()
    kw = keyword.strip()
    if bn == kw:
        return True
    if bn.lower() == kw.lower():
        return True
    # 前缀匹配时，要求关键词后紧跟分隔符，防止「统一」匹配「统一润滑油」
    if bn.lower().startswith(kw.lower()):
        rest = bn[len(kw):]
        return rest[0] in ' （(【「ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz' if rest else True
    return False


async def main():
    domestic_keywords = [(kw, note) for kw, note in DOMESTIC]
    blacklist_keywords = [(kw, note) for kw, note in BLACKLIST]

    # 去重：同一 keyword 可能重复出现在列表里
    seen_domestic = {}
    for kw, note in domestic_keywords:
        if kw not in seen_domestic:
            seen_domestic[kw] = note

    seen_blacklist = {}
    for kw, note in blacklist_keywords:
        if kw not in seen_blacklist:
            seen_blacklist[kw] = note

    async with AsyncSessionLocal() as db:
        all_brands = (await db.execute(select(Brand))).scalars().all()
        print(f"共 {len(all_brands)} 个品牌，开始匹配…")

        domestic_hits = []
        blacklist_hits = []

        for brand in all_brands:
            # 检查国货之光
            for kw, note in seen_domestic.items():
                if name_matches(brand.name, kw):
                    domestic_hits.append((brand, note))
                    break

            # 检查避雷
            for kw, note in seen_blacklist.items():
                if name_matches(brand.name, kw):
                    blacklist_hits.append((brand, note))
                    break

        print(f"\n✅ 国货之光 匹配到 {len(domestic_hits)} 条")
        print(f"⚠️  避雷    匹配到 {len(blacklist_hits)} 条")

        if DRY_RUN:
            print("\n── Dry-run 模式，仅打印，不写库 ──")
            print("\n国货之光 样本（前30条）:")
            for brand, _ in domestic_hits[:30]:
                print(f"  {brand.name}")
            print("\n避雷 样本:")
            for brand, note in blacklist_hits:
                print(f"  {brand.name}  →  {note[:50]}")
            return

        # ── 写库 ──────────────────────────────────────────────────
        updated_domestic = 0
        updated_blacklist = 0

        for brand, note in domestic_hits:
            existing_tags = brand.tags or []
            if "国货之光" not in existing_tags:
                brand.tags = existing_tags + ["国货之光"]
                updated_domestic += 1
            # 只有在没有 note 的情况下才补写（避雷品牌的 note 不会走到这里）
            if not brand.brand_note and note:
                brand.brand_note = note

        removed_domestic_tag = 0
        for brand, note in blacklist_hits:
            existing_tags = brand.tags or []
            # 避雷优先级高于国货之光：如有国货之光标签一并移除（消除矛盾）
            if "国货之光" in existing_tags:
                existing_tags = [t for t in existing_tags if t != "国货之光"]
                removed_domestic_tag += 1
            if "避雷" not in existing_tags:
                existing_tags = existing_tags + ["避雷"]
                updated_blacklist += 1
            brand.tags = existing_tags
            # 避雷榜 note 始终覆盖，确保展示的是警示原因而非推广文案
            if note:
                brand.brand_note = note

        await db.commit()
        print(f"\n写库完成：")
        print(f"  国货之光 新增标注 {updated_domestic} 条")
        print(f"  避雷     新增标注 {updated_blacklist} 条")
        if removed_domestic_tag:
            print(f"  国货之光 因矛盾被移除 {removed_domestic_tag} 条（品牌同时在避雷榜中）")


if __name__ == "__main__":
    asyncio.run(main())
